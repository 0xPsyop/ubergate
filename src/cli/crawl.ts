// CLI command for crawling OpenAPI specs
// Control plane component

import * as fs from 'fs';
import * as path from 'path';
import { parse as parseYaml, stringify as stringifyYaml } from 'yaml';
import { crawlOpenApiSpec } from '../crawler/openapi.js';
import { mergeTools } from '../crawler/merge.js';
import { enrichToolDescriptions } from '../crawler/enrich.js';
import type { ToolsConfig, Tool } from '../types.js';

export interface CrawlOptions {
  specPath: string;
  server: string;
  out?: string;
  owner?: string;
  enrich?: boolean;
}

export async function crawlCommand(options: CrawlOptions): Promise<void> {
  const { specPath, server, out = 'config/tools.yaml', owner = 'unassigned', enrich = false } = options;

  // Load existing tools if present
  let existingTools: Tool[] = [];
  if (fs.existsSync(out)) {
    const existingContent = fs.readFileSync(out, 'utf-8');
    const existing = parseYaml(existingContent) as ToolsConfig;
    if (existing && existing.tools) {
      existingTools = existing.tools;
    }
  }

  // Crawl new tools
  const crawledTools = await crawlOpenApiSpec(specPath, server);

  // Enrich if requested
  let finalCrawled = crawledTools;
  if (enrich) {
    try {
      finalCrawled = await enrichToolDescriptions(crawledTools);
    } catch (error) {
      console.error(`Enrichment failed: ${error instanceof Error ? error.message : String(error)}`);
      process.exit(1);
    }
  }

  // Merge
  const { tools: mergedTools, result } = mergeTools(existingTools, finalCrawled, server, owner);

  // Ensure output directory exists
  const outDir = path.dirname(out);
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  // Write output
  const output: ToolsConfig = {
    version: 1,
    tools: mergedTools,
  };

  const header = '# Generated by ubergate crawl. Enable tools by setting enabled: true via pull request.\n';
  fs.writeFileSync(out, header + stringifyYaml(output));

  // Print summary
  console.log(`Crawl complete:`);
  console.log(`  New: ${result.new}`);
  console.log(`  Unchanged: ${result.unchanged}`);
  console.log(`  Changed (needs review): ${result.changed}`);
  console.log(`  Deprecated: ${result.deprecated}`);
}
